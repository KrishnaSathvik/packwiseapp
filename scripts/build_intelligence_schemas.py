#!/usr/bin/env python3
"""Generate the API's runtime artifacts from the shared source of truth.

`shared/contracts/intelligence-api.yaml` stays the human-facing spec. This
emits what the deployed functions actually load, into `api/generated/`, so
production never reaches sideways into `../shared` at runtime:

  schemas/api.schema.json                  client <-> PackWise API. Full JSON Schema.
  schemas/model-output/<capability>.json   PackWise API <-> model. One strict schema
                                           per capability, restricted to the OpenAI
                                           Structured Outputs subset: every property
                                           required, additionalProperties false, no
                                           numeric/string constraint keywords,
                                           optionality as a nullable type.
  vocab/*.json                             closed vocabularies: canonical item IDs,
                                           context chips, activities, reason codes.
  manifest.json                            schemaVersion and a content buildHash.

Closed vocabularies come from `shared/rules/`, so the model physically cannot
return a chip, activity, or reason code the app does not know.

Run `python3 scripts/build_intelligence_schemas.py`; `validate_shared.py` fails
if the checked-in artifacts no longer match.
"""

