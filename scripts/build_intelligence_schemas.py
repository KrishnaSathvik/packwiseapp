def canonical_items() -> list[str]:
    ids: list[str] = []
    for path in sorted((SHARED / "catalog").glob("*.json")):
        ids.extend(item["id"] for item in load(path)["items"])
    return sorted(ids)


def render() -> dict[Path, str]:
    """Only the runtime artifacts the API needs, each self-contained."""
    vocab = vocabularies()
    files: dict[Path, str] = {}

    def write(relative: str, payload) -> None:
        files[OUT_DIR / relative] = json.dumps(payload, indent=2) + "\n"

    write("schemas/api.schema.json", api_schema(vocab))

    # One strict schema per capability: the Responses API takes a single schema
    # per request, so the combined document is split rather than $ref'd.
    combined = model_output_schema(vocab)
    for capability, definition in CAPABILITY_SCHEMAS.items():
        schema = dict(combined["$defs"][definition])
        schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        schema["title"] = definition
        write(f"schemas/model-output/{capability}.schema.json", schema)

    write("vocab/canonical-items.json", {"items": canonical_items()})
    write("vocab/context-chips.json", {"chips": vocab["contextChips"]})
    write("vocab/activities.json", {"activities": vocab["activities"]})
    reasons = load(SHARED / "rules" / "reasons.json")["templates"]
    write(
        "vocab/reason-codes.json",
        {
            "all": sorted(reasons),
            "gaps": vocab["gapReasonCodes"],
            "optimize": vocab["optimizeReasonCodes"],
            "arguments": {code: placeholders(body) for code, body in sorted(reasons.items())},
        },
    )

    # A content hash, not a timestamp, so the artifact is reproducible and
    # --check stays meaningful.
    digest = hashlib.sha256()
    for path in sorted(files):
        digest.update(path.name.encode())
        digest.update(files[path].encode())

    files[OUT_DIR / "manifest.json"] = (
        json.dumps(
            {
                "schemaVersion": SCHEMA_VERSION,
                "buildHash": digest.hexdigest()[:16],
                "capabilities": {
                    capability: {
                        "schema": f"schemas/model-output/{capability}.schema.json",
                        "definition": definition,
                    }
                    for capability, definition in CAPABILITY_SCHEMAS.items()
                },
            },
            indent=2,
        )
        + "\n"
    )
    return files


def main(argv: list[str]) -> int:
    check = "--check" in argv
    stale: list[str] = []
    for path, body in render().items():
        if check:
            if not path.exists() or path.read_text() != body:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body)
    if stale:
        print("stale generated artifacts: " + ", ".join(stale), file=sys.stderr)
        print("run python3 scripts/build_intelligence_schemas.py", file=sys.stderr)
        return 1
    if not check:
        print(f"OK: wrote {len(render())} generated files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
