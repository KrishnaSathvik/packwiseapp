def load(path: Path):
    return json.loads(path.read_text())


def placeholders(template: str) -> list[str]:
    return sorted(set(re.findall(r"\{(\w+)\}", template)))


def reason_arguments(reasons: dict[str, str], prefix: str) -> dict[str, list[str]]:
    return {code: placeholders(body) for code, body in sorted(reasons.items()) if code.startswith(prefix)}


def vocabularies() -> dict[str, list[str]]:
    base = load(SHARED / "rules" / "base.json")
    activities = load(SHARED / "rules" / "activity-rules.json")["activities"]
    reasons = load(SHARED / "rules" / "reasons.json")["templates"]
    return {
        "contextChips": sorted(base["context_chips"]),
        "activities": sorted(activities),
        "gapReasonCodes": sorted(k for k in reasons if k.startswith("context.gap_")),
        "optimizeReasonCodes": sorted(k for k in reasons if k.startswith("context.optimize_")),
        "gapArguments": reason_arguments(reasons, "context.gap_"),
        "optimizeArguments": reason_arguments(reasons, "context.optimize_"),
    }


